import random


def random_node_name(i):
    return f"N{str(i).zfill(2)}"


def generate_edge(mode):
    if mode == 'road':
        return random.randint(5, 10), random.randint(10, 50), mode
    elif mode == 'air':
        return random.randint(1, 4), random.randint(150, 300), mode
    else:
        return random.randint(3, 7), random.randint(60, 150), mode


def generate_graph_by_level(idx):

    if idx <= 5:
        num_nodes = 6
        tradeoff = False
        cycles = False
    elif idx <= 10:
        num_nodes = 8
        tradeoff = True
        cycles = False
    elif idx <= 15:
        num_nodes = 15
        tradeoff = True
        cycles = True
    else:
        num_nodes = 17
        tradeoff = True
        cycles = True

    nodes = ['A'] + [random_node_name(i) for i in range(1, num_nodes - 1)] + ['T']
    graph = {n: [] for n in nodes}
    positions = {}

    for i, n in enumerate(nodes):
        positions[n] = (i * 2, random.uniform(-5, 5))


    for i in range(len(nodes) - 1):
        u = nodes[i]
        v = nodes[i + 1]

        if tradeoff:
            for mode in ['road', 'air',"ship"]:
                t, c, m = generate_edge(mode)
                graph[u].append((v, t, c, m))
        else:
            t = random.randint(2, 6)
            c = t * 20
            graph[u].append((v, t, c, 'road'))

    extra_edges = idx * 2
    for _ in range(extra_edges):
        u = random.choice(nodes[:-1])
        v = random.choice(nodes[1:])
        if u == v:
            continue

        mode = random.choice(['road', 'air', 'water'])
        graph[u].append((v, *generate_edge(mode)))


    if cycles:
        for _ in range(idx):
            u = random.choice(nodes)
            v = random.choice(nodes)
            if u != v:
                graph[u].append((v, *generate_edge('road')))

    Tmax = random.randint(8, 15) if idx <= 10 else random.randint(10, 25)
    P = random.randint(100, 300) if idx <= 10 else random.randint(150, 500)

    return {
        'id': f"G{str(idx).zfill(2)}",
        'size_group': (
            'small' if num_nodes <= 8 else
            'medium' if num_nodes <= 13 else
            'large'
        ),
        'tradeoff': tradeoff,
        'nodes': num_nodes,
        'start': 'A',
        'goal': 'T',
        'Tmax': Tmax,
        'P': P,
        'positions': positions,
        'graph': graph
    }

def generate_full_dataset(n=20):
    return [generate_graph_by_level(i) for i in range(1, n + 1)]

